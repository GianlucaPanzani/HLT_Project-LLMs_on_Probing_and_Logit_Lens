                "    sentences = table_to_sentences(table)\n",
                "    sent_groups = dict(tuple(table.groupby(\"sent_id\", sort=False)))\n",
                "\n",
                "    batches: list[dict] = []\n",
                "    for i in range(0, len(sentences), batch_size):\n",
                "        chunk = sentences[i : i + batch_size]\n",
                "        seq_ids = [s_id for s_id, _ in chunk]\n",
