                "def prepare_pud_batches(treebank: str, tokenizer, *, batch_size: int = 16) -> list[dict]:\n",
                "    \"\"\"Prepare PUD evaluation batches with word-to-subword alignment for UPOS evaluation.\"\"\"\n",
